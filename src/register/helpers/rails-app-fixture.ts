// A Rails application that genuinely boots, connects to PostgreSQL and
// talks to Redis - for the one test that runs the real Inspector against
// what `fabrica register` writes (issue #337, `inspector-e2e.test.ts`).
//
// Deliberately a different fixture from `rails-fixture.ts`, which is a
// handful of files that exist only to be *read* by `register`'s own
// rules. This one has to run, so every file here is a file a `rails new`
// application really has, trimmed to what a suite needs: no assets, no
// Action Cable, no system tests, no credentials.
//
// Three things about it are load-bearing rather than incidental, and a
// trimmed-down version that lost any of them would prove less than it
// looks like it proves:
//
//   - **`log/` and `tmp/` are tracked, the way `rails new` tracks them**
//     (a `.keep` in each, with `/log/*` and `/tmp/*` ignored around it).
//     That is what makes them read-only inside Inspector's check box,
//     which is the thing issue #337's fourth finding is about.
//   - **Bootsnap is really in it**, required from `config/boot.rb`. It
//     is the one thing that stops a Rails boot dead when `tmp/cache`
//     cannot be written, so the generated `check.sh`'s
//     `BOOTSNAP_CACHE_DIR` has something to actually prevent.
//   - **One spec uses the database and one uses Redis.** A suite that
//     touched neither would pass in a box where neither server ever
//     started.
//   - **One gem lives in the repository**, `engines/prototypes`, named
//     with `path:`. The Client's own work repository has one, and
//     `bundle install` stopped dead on it: a `path:` gem resolves
//     relative to the directory holding the Gemfile, which during the
//     image build is `/deps`, so the generated Dockerfile has to copy
//     that directory in. Without it in this fixture, nothing here would
//     have noticed.
//
// `Gemfile.lock` is not here: it is generated by a real `bundle lock`
// before the fixture is committed (see the e2e test), because a
// hand-written one bundler decided to re-resolve would mean the image
// installed something other than what this says it pins.

import { chmodSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

/**
 * The Ruby this fixture pins, and so - through `.ruby-version` - the
 * `ruby:<version>` image `register` derives for it. An exact patch
 * version, because that is the only thing `register` turns into an
 * image tag at all.
 */
export const FIXTURE_RUBY_VERSION = "3.3.12";

/** The Rails line the fixture is written against. `config.load_defaults`
 * and `ActiveRecord::Schema[...]` both name a version, so the Gemfile
 * pins the same one rather than floating. */
export const FIXTURE_RAILS_VERSION = "8.0";

/** The gem the fixture keeps in the repository itself, and the path the
 * Gemfile names it by. Exported because two tests assert on the `COPY`
 * the generated Dockerfile has to write for it. */
export const FIXTURE_PATH_GEM = "prototypes";
/** @see FIXTURE_PATH_GEM */
export const FIXTURE_PATH_GEM_DIR = `engines/${FIXTURE_PATH_GEM}`;

/** The image the check box is built from, which is what `register`
 * derives from `.ruby-version` above. Named here so the test that runs
 * `bundle lock` resolves the lockfile against the same Ruby the image
 * will install the gems with. */
export const FIXTURE_IMAGE = `ruby:${FIXTURE_RUBY_VERSION}`;

/**
 * Every file the application is made of, by repository-relative path.
 *
 * `bin/rails` needs its executable bit, which `writeRailsApp` sets - a
 * generated `check.sh` runs `bin/rails db:test:prepare` as a program,
 * exactly as Rails' own documentation does.
 */
export function railsAppFiles(): Record<string, string> {
  return {
    // `rails new`'s own treatment of these two directories, which is the
    // whole reason this fixture exists: git tracks the `.keep` files, so
    // Inspector mounts both directories read-only.
    ".gitignore": `/.bundle\n/log/*\n!/log/.keep\n/tmp/*\n!/tmp/.keep\n`,
    "log/.keep": ``,
    "tmp/.keep": ``,

    ".ruby-version": `${FIXTURE_RUBY_VERSION}\n`,

    Gemfile:
      `source "https://rubygems.org"\n` +
      `\n` +
      `gem "rails", "~> ${FIXTURE_RAILS_VERSION}.0"\n` +
      `gem "pg", "~> 1.5"\n` +
      `gem "redis", "~> 5.0"\n` +
      `# Required from config/boot.rb, as \`rails new\` requires it: this is\n` +
      `# the one thing that fails a boot outright when tmp/ cannot be\n` +
      `# written.\n` +
      `gem "bootsnap", require: false\n` +
      `# A gem kept in this repository rather than fetched. The generated\n` +
      `# Dockerfile has to copy this directory into the build, or\n` +
      `# \`bundle install\` stops on "does not exist" before it installs\n` +
      `# anything.\n` +
      `gem "${FIXTURE_PATH_GEM}", path: "${FIXTURE_PATH_GEM_DIR}"\n` +
      `\n` +
      `group :test do\n` +
      `  gem "rspec"\n` +
      `end\n`,

    // The path gem itself. A plain gem rather than a Rails engine:
    // what is being proved is that `bundle install` finds the directory,
    // and an engine's railtie would add a second thing that could fail
    // for an unrelated reason.
    [`${FIXTURE_PATH_GEM_DIR}/${FIXTURE_PATH_GEM}.gemspec`]:
      `Gem::Specification.new do |spec|\n` +
      `  spec.name        = "${FIXTURE_PATH_GEM}"\n` +
      `  spec.version     = "0.1.0"\n` +
      `  spec.authors     = ["The Client"]\n` +
      `  spec.email       = ["client@example.test"]\n` +
      `  spec.summary     = "A gem this repository keeps to itself."\n` +
      `  spec.description = "Proves a path: gem reaches the check box."\n` +
      `  spec.homepage    = "https://example.test/${FIXTURE_PATH_GEM}"\n` +
      `  spec.license     = "MIT"\n` +
      // Dir rather than `git ls-files`, which is what `rails plugin new`
      // writes: there is no git repository where this gemspec is
      // evaluated during the image build.
      `  spec.files       = Dir.chdir(File.expand_path(__dir__)) { Dir["lib/**/*"] }\n` +
      `  spec.require_paths = ["lib"]\n` +
      `end\n`,

    [`${FIXTURE_PATH_GEM_DIR}/lib/${FIXTURE_PATH_GEM}.rb`]:
      `module Prototypes\n  VERSION = "0.1.0"\n\n  def self.name_plate\n    "spindle"\n  end\nend\n`,

    Rakefile: `require_relative "config/application"\n\nRails.application.load_tasks\n`,

    "bin/rails":
      `#!/usr/bin/env ruby\n` +
      `APP_PATH = File.expand_path("../config/application", __dir__)\n` +
      `require_relative "../config/boot"\n` +
      `require "rails/commands"\n`,

    "config/boot.rb":
      `ENV["BUNDLE_GEMFILE"] ||= File.expand_path("../Gemfile", __dir__)\n` +
      `\n` +
      `require "bundler/setup"\n` +
      `require "bootsnap/setup"\n`,

    "config/application.rb":
      `require_relative "boot"\n` +
      `\n` +
      `require "rails"\n` +
      `require "active_record/railtie"\n` +
      `\n` +
      `Bundler.require(*Rails.groups)\n` +
      `\n` +
      `module FixtureApp\n` +
      `  class Application < Rails::Application\n` +
      `    config.load_defaults ${FIXTURE_RAILS_VERSION}\n` +
      `    config.eager_load = false\n` +
      `  end\n` +
      `end\n`,

    "config/environment.rb": `require_relative "application"\n\nRails.application.initialize!\n`,

    // Both environments, the way `rails new` writes both. The generated
    // check.sh exports RAILS_ENV=test, so development.rb is not what any
    // of this runs in - it stays because an application missing one of
    // its own environment files is not the shape this fixture is for.
    "config/environments/development.rb": environmentFile(),
    "config/environments/test.rb": environmentFile(),

    // No host and no username, exactly as `rails new -d postgresql`
    // writes it - which is what makes the PGHOST and PGUSER the
    // generated check.sh exports the ones libpq uses.
    "config/database.yml":
      `default: &default\n` +
      `  adapter: postgresql\n` +
      `  encoding: unicode\n` +
      `  pool: 5\n` +
      `\n` +
      `development:\n` +
      `  <<: *default\n` +
      `  database: fixture_development\n` +
      `\n` +
      `test:\n` +
      `  <<: *default\n` +
      `  database: fixture_test\n`,

    "db/schema.rb":
      `ActiveRecord::Schema[${FIXTURE_RAILS_VERSION}].define(version: 1) do\n` +
      `  create_table "widgets", force: :cascade do |t|\n` +
      `    t.string "name"\n` +
      `    t.datetime "created_at", null: false\n` +
      `    t.datetime "updated_at", null: false\n` +
      `  end\n` +
      `end\n`,

    "app/models/application_record.rb":
      `class ApplicationRecord < ActiveRecord::Base\n  primary_abstract_class\nend\n`,
    "app/models/widget.rb": `class Widget < ApplicationRecord\nend\n`,

    ".rspec": `--require spec_helper\n`,
    "spec/spec_helper.rb":
      `ENV["RAILS_ENV"] ||= "test"\n` +
      `\n` +
      `require_relative "../config/environment"\n`,

    // The database one. It writes a row and reads it back, so a box
    // where PostgreSQL never started, or where the test schema was never
    // loaded, fails here.
    "spec/widget_spec.rb":
      `RSpec.describe Widget do\n` +
      `  it "writes a row and reads it back" do\n` +
      `    widget = Widget.create!(name: "spindle")\n` +
      `\n` +
      `    expect(Widget.find(widget.id).name).to eq("spindle")\n` +
      `  end\n` +
      `end\n`,

    // The Redis one. Redis.new with no arguments is 127.0.0.1:6379,
    // which is where the generated check.sh starts it.
    "spec/redis_spec.rb":
      `require "redis"\n` +
      `\n` +
      `RSpec.describe "Redis" do\n` +
      `  it "sets a key and gets it back" do\n` +
      `    redis = Redis.new\n` +
      `    redis.set("fabrica:fixture", "ok")\n` +
      `\n` +
      `    expect(redis.get("fabrica:fixture")).to eq("ok")\n` +
      `  end\n` +
      `end\n`,

    // The path gem one. `Bundler.require` in config/application.rb
    // already requires it, so a box where the gem never made it in
    // fails before this runs - this says which gem, rather than leaving
    // a boot error to be read.
    "spec/prototypes_spec.rb":
      `RSpec.describe Prototypes do\n` +
      `  it "is the gem this repository keeps to itself" do\n` +
      `    expect(Prototypes.name_plate).to eq("spindle")\n` +
      `  end\n` +
      `end\n`,
  };
}

/** One environment file, the same for development and test: reloading
 * and eager loading off, and no cache store, which is every setting a
 * suite with no web requests in it actually reads. */
function environmentFile(): string {
  return (
    `Rails.application.configure do\n` +
    `  config.enable_reloading = false\n` +
    `  config.eager_load = false\n` +
    `  config.cache_store = :null_store\n` +
    `end\n`
  );
}

/** Writes the application into `dir`, creating the directories nested
 * paths need and setting `bin/rails` executable. Committing it is the
 * caller's business - and a caller has a `bundle lock` to run first. */
export function writeRailsApp(dir: string, files = railsAppFiles()): void {
  for (const [name, contents] of Object.entries(files)) {
    const path = join(dir, name);
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, contents);
  }
  chmodSync(join(dir, "bin/rails"), 0o755);
}
